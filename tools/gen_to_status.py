#!/usr/bin/env python3
"""Write `hf::ToStatus()` for every `hf_*_err_t`, next to its error list in inc/base/Base*.h.

The codes come from each header's `HF_<X>_ERR_LIST(X)` table (plus any enumerator written after the
table, such as a `*_ERR_COUNT` sentinel). The mapping onto `hf::Status` applies the name rules of the
HardFOC standard (standards/errors.md in hardfoc/.github), written out in RULES below. Each code gets
its own `case` and the switch has no `default`, so a code added to a table without regenerating is a
-Wswitch error, and the `to_status_fresh` host test fails.

The generated block sits between two marker lines right after the enum; everything else in the
header is left alone.

Usage:
  python3 tools/gen_to_status.py           rewrite the headers
  python3 tools/gen_to_status.py --check   exit 1 when a header is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "inc" / "base"
BEGIN = "// --- hf::ToStatus(), generated by tools/gen_to_status.py: do not edit ---"
END = "// --- end of generated hf::ToStatus() ---"
INCLUDE = '#include "hf/iiw/Status.h"'

# standards/errors.md, "Interface-wrap codes to hf::Status", in its order: the first rule that matches
# the code's name (without the SPI_ERR_ / SPI_ prefix) wins. The Bus row also takes the transfer
# failures the Status definition lists (framing, parity, overrun, checksum, CAN frame errors).
RULES = (
    (r"^SUCCESS$", "Ok"),
    (r"NOT_INITIALIZED", "NotInitialized"),
    (r"INVALID|NULL_POINTER", "InvalidArgument"),
    (r"BUSY|ALREADY_INITIALIZED", "Busy"),
    (r"TIMEOUT", "Timeout"),
    (r"BUS_ERROR|TRANSFER_FAILED|COMMUNICATION_FAILURE|NACK|ARBITRATION_LOST|CRC|CS_CONTROL_FAILED"
     r"|FRAME_ERROR|PARITY_ERROR|OVERRUN|NOISE_ERROR|CHECKSUM|STUFF_ERROR|FORM_ERROR|ACK_ERROR|BIT_ERROR"
     r"|TRANSMISSION_FAILED|RECEPTION_FAILED|READ_FAILURE|WRITE_FAILURE|CHANNEL_READ_ERR|CHANNEL_WRITE_ERR",
     "Bus"),
    (r"DEVICE_NOT_FOUND|DEVICE_NOT_RESPONDING|NOT_AVAILABLE|_NOT_FOUND$|^NOT_FOUND$", "NotFound"),
    (r"HARDWARE_FAULT|HARDWARE_FAILURE|VOLTAGE_OUT_OF_RANGE|CLOCK_ERROR", "Fault"),
    (r"UNSUPPORTED_OPERATION|NOT_SUPPORTED", "Unsupported"),
    (r"OUT_OF_MEMORY|NO_MEMORY", "NoMemory"),
)

LIST_RE = re.compile(r"^#define (HF_(\w+)_ERR_LIST)\(X\)[ \t]*\\\n(.*?)(?<!\\)\n(?=\S|\n)", re.M | re.S)
ENTRY_RE = re.compile(r"X\((\w+),\s*(-?\d+)\s*,")


def classify(name: str, prefix: str) -> str:
    key = name
    for p in (prefix + "_ERR_", prefix + "_"):
        if key.startswith(p):
            key = key[len(p):]
            break
    for pattern, status in RULES:
        if re.search(pattern, key):
            return status
    return "Unknown"


def tables(text: str, header: str) -> list[dict]:
    out = []
    for m in LIST_RE.finditer(text):
        macro, prefix, body = m.group(1), m.group(2), m.group(3)
        enum = re.search(rf"enum class (hf_\w+_err_t)\b[^{{;]*\{{([^}}]*{macro}[^}}]*)\}};", text, re.S)
        if enum:
            name, enum_body, end = enum.group(1), enum.group(2), enum.end()
        else:
            enum = re.search(rf"typedef enum\s*\{{([^}}]*{macro}[^}}]*)\}}\s*(hf_\w+_err_t)\s*;", text, re.S)
            if not enum:
                raise SystemExit(f"[gen_to_status] {header}: no enum built from {macro}")
            name, enum_body, end = enum.group(2), enum.group(1), enum.end()
        entries = [(n, int(v)) for n, v in ENTRY_RE.findall(body)]
        rest = re.sub(r"/\*.*?\*/", "", enum_body, flags=re.S)
        rest = re.sub(r"//[^\n]*|^[ \t]*#[^\n]*", "", rest, flags=re.M).replace(macro, "")
        rest = re.sub(r"\(\s*\w+\s*\)", "", rest)
        nxt = max(v for _n, v in entries) + 1
        for extra in re.findall(r"\b([A-Z][A-Z0-9_]+)\b", rest):
            entries.append((extra, nxt))
            nxt += 1
        values = [v for _n, v in entries]
        if len(values) != len(set(values)):
            raise SystemExit(f"[gen_to_status] {header}: {name} repeats a value; a switch cannot list both")
        out.append({"enum": name, "end": end,
                    "codes": [(n, v, classify(n, prefix)) for n, v in entries]})
    return out


def block(t: dict) -> str:
    e = t["enum"]
    lines = [BEGIN, "namespace hf {", "", f"/// `hf::Status` for an `{e}` (standards/errors.md).",
             f"[[nodiscard]] constexpr Status ToStatus({e} error) noexcept {{", "  switch (error) {"]
    for name, value, status in t["codes"]:
        lines += [f"  case {e}::{name}: // {value}", f"    return Status::{status};"]
    lines += ["  }", "  return Status::Unknown;", "}", "", "} // namespace hf", END]
    return "\n".join(lines)


def regenerate(text: str, header: str) -> str:
    text = re.sub(rf"\n\n{re.escape(BEGIN)}.*?{re.escape(END)}", "", text, flags=re.S)
    ts = tables(text, header)
    if not ts:
        return text
    for t in sorted(ts, key=lambda t: t["end"], reverse=True):
        text = text[: t["end"]] + "\n\n" + block(t) + text[t["end"]:]
    if INCLUDE not in text:
        anchor = '#include "HardwareTypes.h"\n'
        if anchor not in text:
            raise SystemExit(f"[gen_to_status] {header}: no HardwareTypes.h include to add Status.h after")
        text = text.replace(anchor, anchor + INCLUDE + "\n", 1)
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when a header is stale")
    args = parser.parse_args()
    stale = []
    for header in sorted(BASE.glob("Base*.h")):
        old = header.read_text(encoding="utf-8")
        new = regenerate(old, header.name)
        if new == old:
            continue
        stale.append(header.name)
        if not args.check:
            header.write_text(new, encoding="utf-8")
            print(f"[gen_to_status] wrote inc/base/{header.name}")
    if args.check and stale:
        print(f"[gen_to_status] stale: {', '.join(stale)}; run python3 tools/gen_to_status.py", file=sys.stderr)
        return 1
    if args.check:
        print("[gen_to_status] every ToStatus() is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
